#!/usr/bin/env python3
"""Compile the canonical CSV catalog into INET application/stream bindings and XML.
Run from any directory. --check detects generated files that are out of date.
"""
import argparse
import csv
from collections import defaultdict
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / 'simulations/zonal/traffic'


def generate():
    flows = list(csv.DictReader((DATA / 'flows.csv').open()))
    signatures = list(csv.DictReader((DATA / 'transients.csv').open()))
    assert [f['flow_id'] for f in flows] == [f'F{i:02}' for i in range(1, 23)]
    assert len(signatures) == 10
    scalable = {1,2,3,4,5,6,7,11,12,13,18,19,20}
    for f in flows:
        fid = int(f['flow_id'][1:])
        app, ip, mac, wire = (int(f[key]) for key in ['app_bytes','ip_bytes','mac_bytes','wire_bytes'])
        if not (ip == app + 28 and mac == max(64, ip + 22) and wire == mac + 20):
            raise ValueError(f"{f['flow_id']}: inconsistent application/IP/MAC/wire lengths")
        if ip > 1500 or int(f['traffic_class']) != int(f['pcp']):
            raise ValueError(f"{f['flow_id']}: MTU or PCP-to-TC mismatch")
        if (f['scalable'] == '1') != (fid in scalable):
            raise ValueError(f"{f['flow_id']}: scaling contradicts P1 section 3.4")
        if f['wire_rate_mbps']:
            derived = int(f['packets_per_cycle']) * wire * 8 / float(f['period_us'])
            if abs(derived - float(f['wire_rate_mbps'])) > 1e-9:
                raise ValueError(f"{f['flow_id']}: nominal rate does not match packetization")
    root = ET.Element('catalog')
    apps = defaultdict(list)
    outgoing = defaultdict(list)
    incoming = defaultdict(list)
    for f in flows:
        fid = int(f['flow_id'][1:])
        attrs = dict(id=str(fid), name=f['flow_id'], source=f['source'],
                     destinations=f['destinations'], family=f['family'],
                     app_bytes=f['app_bytes'], burst=f['packets_per_cycle'],
                     pcp=f['pcp'], vlan=f['vlan'], scalable=f['scalable'],
                     period=str(float(f['period_us']) / 1e6),
                     offset=str(float(f['offset_us']) / 1e6),
                     phase=str(int(f['phase_numerator']) / int(f['phase_denominator'])),
                     deadline=str(float(f['deadline_us'] or 0) / 1e6), criticality=f['criticality'])
        ET.SubElement(root, 'flow', attrs)
        apps[f['source']].append((fid, True))
        outgoing[f['source']].append(f)
        for dst in f['destinations'].split(';'):
            apps[dst].append((fid, False))
            incoming[dst].append(f)
    for s in signatures:
        ET.SubElement(root, 'signature', name=s['signature_id'],
                      duration=str(float(s['duration_ms']) / 1000), volume=s['volume_bytes'])
    ET.indent(root)
    xml = ET.tostring(root, encoding='unicode') + '\n'
    ini = ['# GENERATED by scripts/catalog/generate.py from traffic/*.csv. Do not edit.',
           '[Config CatalogBindings]', '*.hasTraffic = true',
           '*.trafficPlan.catalog = xmldoc("../traffic/catalog.xml")']
    for node, bindings in apps.items():
        ini += ['', f'# {node}: one application per flow and role', f'*.{node}.numApps = {len(bindings)}',
                f'*.{node}.app[*].typename = "CatalogUdpApp"']
        for i, (fid, source) in enumerate(bindings):
            ini += [f'*.{node}.app[{i}].flowId = {fid}',
                    f'*.{node}.app[{i}].source = {str(source).lower()}',
                    f'*.{node}.app[{i}].display-name = "F{fid:02} {"TX" if source else "RX"}"']
        if outgoing[node]:
            identify = ', '.join('{stream: "%s", packetFilter: expr(udp.destPort == %d)}' %
                                 (f['flow_id'], 5000 + int(f['flow_id'][1:])) for f in outgoing[node])
            encode = ', '.join('{stream: "%s", vlan: %s, pcp: %s}' %
                               (f['flow_id'], f['vlan'], f['pcp']) for f in outgoing[node])
            ini += [f'*.{node}.hasOutgoingStreams = true',
                    f'*.{node}.bridging.streamIdentifier.identifier.mapping = [{identify}]',
                    f'*.{node}.bridging.streamCoder.encoder.mapping = [{encode}]']
        if incoming[node]:
            decode = ', '.join('{stream: "%s", vlan: %s, pcp: %s}' %
                               (f['flow_id'], f['vlan'], f['pcp']) for f in incoming[node])
            ini += [f'*.{node}.hasIncomingStreams = true',
                    f'*.{node}.bridging.streamCoder.decoder.mapping = [{decode}]']
    # VLAN-aware static forwarding. INET's automatic MAC configurator installs
    # untagged entries; using those for this tagged catalog would cause flooding.
    zones = {
        'Z1': ['LiDAR1','CAM1','BRAKE1','WINDOW1','AUDIO1','DISPLAY1','BE1'],
        'Z2': ['RADAR1','CAM2','BRAKE2','WINDOW2','AUDIO2','DISPLAY2','BE2'],
        'Z3': ['RADAR2','CAM3','CAM4','BRAKE3','WINDOW3','AUDIO3','BE3'],
    }
    def port(switch, destination):
        if destination == 'HPC':
            return 0
        zone = next(z for z, devices in zones.items() if destination in devices or destination == z + '.ZCPU')
        if switch == 'CSW':
            return int(zone[1])
        if not switch.startswith(zone):
            return 0
        return 1 if destination.endswith('.ZCPU') else zones[zone].index(destination) + 2
    for switch in ['CSW', 'Z1.ZSW', 'Z2.ZSW', 'Z3.ZSW']:
        entries = ['{address: "%s", interface: "eth%d", vlan: %s}' %
                   (f['destinations'], port(switch, f['destinations']), f['vlan'])
                   for f in flows if f['flow_id'] != 'F14']
        for output in {'CSW': [1,2], 'Z1.ZSW': [7], 'Z2.ZSW': [7], 'Z3.ZSW': []}[switch]:
            entries.append('{address: "01-00-5E-00-00-0E", interface: "eth%d", vlan: 10}' % output)
        ini += ['', f'*.{switch}.macTable.forwardingTable = [' + ', '.join(entries) + ']']
    return {DATA / 'catalog.xml': xml,
            ROOT / 'simulations/zonal/configs/catalog-bindings.ini': '\n'.join(ini) + '\n'}


if __name__ == '__main__':
    args = argparse.ArgumentParser(description=__doc__)
    args.add_argument('--check', action='store_true')
    check = args.parse_args().check
    for path, content in generate().items():
        if check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Out of date: {path}')
        else:
            path.write_text(content)
    print('Catalog generated files are consistent.' if check else 'Generated catalog.xml and catalog-bindings.ini.')

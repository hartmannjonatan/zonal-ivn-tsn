#!/usr/bin/env python3
"""Generate P1 C2 nominal CBS reservations from the canonical traffic catalog."""
import argparse
import csv
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FLOWS = ROOT / "simulations/zonal/traffic/flows.csv"
INI_OUT = ROOT / "simulations/zonal/configs/mechanisms/C2_nominal_rates.ini"
CSV_OUT = ROOT / "simulations/zonal/traffic/cbs_nominal_reservations.csv"
LOAD_FACTORS = (0.5, 1.0, 2.5, 4.0)
ZONES = {
    "Z1": ["LiDAR1", "CAM1", "BRAKE1", "WINDOW1", "AUDIO1", "DISPLAY1", "BE1"],
    "Z2": ["RADAR1", "CAM2", "BRAKE2", "WINDOW2", "AUDIO2", "DISPLAY2", "BE2"],
    "Z3": ["RADAR2", "CAM3", "CAM4", "BRAKE3", "WINDOW3", "AUDIO3", "BE3"],
}


def zone(node):
    for name, devices in ZONES.items():
        if node in devices or node == name + ".ZCPU":
            return name
    raise ValueError(f"Unknown zonal endpoint {node}")


def port(node, index):
    return f"{node}.eth[{index}]"


def access_port(node):
    # The zonal processing endpoint is attached to ZSW.eth[1]; access-array
    # sensors begin at eth[2].
    if node.endswith(".ZCPU"):
        return 1
    return ZONES[zone(node)].index(node) + 2


def route(source, destination):
    path = [port(source, 0)]
    if source == "HPC":
        z = zone(destination)
        return path + [port("CSW", int(z[1])), port(z + ".ZSW", access_port(destination))]
    source_zone = zone(source)
    if destination == "HPC":
        return path + [port(source_zone + ".ZSW", 0), port("CSW", 0)]
    destination_zone = zone(destination)
    if destination_zone == source_zone:
        return path + [port(destination_zone + ".ZSW", access_port(destination))]
    return path + [port(source_zone + ".ZSW", 0), port("CSW", int(destination_zone[1])),
                   port(destination_zone + ".ZSW", access_port(destination))]


def read_flows():
    with FLOWS.open(newline="") as stream:
        return list(csv.DictReader(stream))


def nominal_reservations(flows):
    """Map (load, egress, TC) to summed permanent P1 wire rate in bit/s."""
    reservations = defaultdict(lambda: {"bps": 0, "flows": set()})
    for load, factor in enumerate(LOAD_FACTORS):
        for flow in flows:
            tc = int(flow["traffic_class"])
            if tc not in (4, 6) or flow["family"] == "transient":
                continue
            rate = float(flow["wire_rate_mbps"]) * (factor if flow["scalable"] == "1" else 1.0)
            rate_bps = round(rate * 1_000_000)
            egresses = set()
            for destination in flow["destinations"].split(";"):
                egresses.update(route(flow["source"], destination))
            for egress in egresses:
                entry = reservations[load, egress, tc]
                entry["bps"] += rate_bps
                entry["flows"].add(flow["flow_id"])
    return reservations


def capacity_bps(egress):
    if egress.startswith(("HPC.", "CSW.", "Z1.ZSW.eth[0]", "Z1.ZSW.eth[1]",
                          "Z2.ZSW.eth[0]", "Z2.ZSW.eth[1]", "Z3.ZSW.eth[0]", "Z3.ZSW.eth[1]",
                          "Z1.ZCPU.", "Z2.ZCPU.", "Z3.ZCPU.")):
        return 1_000_000_000
    if egress.startswith(("CAM", "LiDAR1.")):
        return 1_000_000_000
    if egress.startswith("RADAR"):
        return 100_000_000
    if ".ZSW.eth[" in egress:
        zsw, port_index = egress.rsplit(".eth[", 1)
        port_index = int(port_index.rstrip("]"))
        access_index = port_index - 2
        endpoints = ZONES[zsw.split(".")[0]]
        return 1_000_000_000 if endpoints[access_index] in ("LiDAR1", "CAM1", "CAM2", "CAM3", "CAM4") else 100_000_000
    if egress.startswith("CSW."):
        return 1_000_000_000
    raise ValueError(f"Unknown interface speed for {egress}")


def render(flows):
    reservations = nominal_reservations(flows)
    rows = []
    ini = [
        "# GENERATED by scripts/catalog/generate_cbs.py from traffic/flows.csv; do not edit.",
        "# P1 C2 nominal permanent wire-rate reservations; transients F21/F22 excluded.",
    ]
    for load in range(4):
        ini += ["", f"[Config C2RatesL{load}]"]
        for (entry_load, egress, tc), entry in sorted(reservations.items()):
            if entry_load != load:
                continue
            bps = entry["bps"]
            bitrate = capacity_bps(egress)
            if bps <= 0 or bps >= bitrate:
                raise ValueError(f"Invalid C2 CBS reservation L{load} {egress} TC{tc}: {bps}/{bitrate} bit/s")
            module = f"*.{egress}.macLayer.queue"
            algorithm = f"{module}.transmissionSelectionAlgorithm[{tc}]"
            ini.append(f'{algorithm}.typename = "Ieee8021qCreditBasedShaper"')
            ini.append(f"{algorithm}.idleSlope = {bps}bps")
            ini.append(f"{algorithm}.numCredits.result-recording-modes = vector,max,min,timeavg")
            rows.append({"load": f"L{load}", "egress": egress, "traffic_class": tc,
                         "idle_slope_bps": bps, "idle_slope_mbps": f"{bps / 1e6:.6f}",
                         "port_rate_bps": bitrate, "reservation_percent": f"{100*bps/bitrate:.4f}",
                         "permanent_flows": ";".join(sorted(entry["flows"]))})
    csv_rows = ["load,egress,traffic_class,idle_slope_bps,idle_slope_mbps,port_rate_bps,reservation_percent,permanent_flows"]
    csv_rows.extend(
        f"{r['load']},{r['egress']},{r['traffic_class']},{r['idle_slope_bps']},{r['idle_slope_mbps']},"
        f"{r['port_rate_bps']},{r['reservation_percent']},{r['permanent_flows']}" for r in rows)
    return "\n".join(ini) + "\n", "\n".join(csv_rows) + "\n", rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated reservations are stale")
    args = parser.parse_args()
    ini, csv_data, rows = render(read_flows())
    outputs = ((INI_OUT, ini), (CSV_OUT, csv_data))
    if args.check:
        stale = [str(path.relative_to(ROOT)) for path, data in outputs
                 if not path.exists() or path.read_text() != data]
        if stale:
            raise SystemExit("Stale C2 CBS reservation artifacts: " + ", ".join(stale))
    else:
        for path, data in outputs:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(data)
    print(f"C2 nominal CBS reservation artifacts {'verified' if args.check else 'generated'}: "
          f"{len(rows)} per-egress/per-class/load entries")


if __name__ == "__main__":
    main()

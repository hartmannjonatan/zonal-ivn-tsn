#!/usr/bin/env python3
"""Generate frozen C3 CBS reservations and enforce P1's per-port 75% cap."""
import argparse
import csv
import json
from collections import defaultdict
from pathlib import Path

from generate_cbs import capacity_bps, nominal_reservations, read_flows

ROOT = Path(__file__).resolve().parents[2]
RATIOS = ROOT / "simulations/zonal/traffic/cbs_calibration.json"
INI_OUT_C3 = ROOT / "simulations/zonal/configs/mechanisms/C3_calibrated_rates.ini"
CSV_OUT = ROOT / "simulations/zonal/traffic/cbs_calibrated_reservations.csv"
SCREEN_OUT = ROOT / "simulations/zonal/traffic/c3_reservation_screen.json"
CAP = 0.75


def load_ratio_data(path=RATIOS):
    data = json.loads(path.read_text())
    ratios = data.get("ratios", {})
    if not isinstance(ratios, dict):
        raise ValueError("calibration JSON must contain a ratios object")
    normalized = {}
    for key, value in ratios.items():
        if "/TC" not in key:
            raise ValueError(f"Invalid ratio key {key!r}; expected EGRESS/TCn")
        egress, tc = key.rsplit("/TC", 1)
        ratio = float(value)
        if ratio < 1 or ratio != ratio or ratio == float("inf"):
            raise ValueError(f"C3 ratio must be finite and >=1: {key}={value}")
        normalized[egress, int(tc)] = ratio
    return data, normalized


def render(path=RATIOS):
    data, ratios = load_ratio_data(path)
    calibration = data.get("calibration", {})
    if not isinstance(calibration, dict):
        calibration = {}
    frozen = bool(calibration.get("freeze_ratios", False))
    nominal = nominal_reservations(read_flows())
    calibrated = {}
    for (load, egress, tc), entry in nominal.items():
        ratio = ratios.get((egress, tc), 1.0)
        calibrated[load, egress, tc] = {
            "nominal_bps": entry["bps"],
            "ratio": ratio,
            "bps": round(entry["bps"] * ratio),
            "flows": sorted(entry["flows"]),
        }
    if frozen:
        status_lines = ["# C3 freezes calibrated-to-nominal ratios from L2/A1; no per-cell clipping."]
    else:
        status_lines = [
            "# DIAGNOSTIC CANDIDATE ONLY: P1 L2/A1 viability calibration did not pass.",
            "# Ratios are not frozen as a validated C3 profile; do not report these runs as C3 validation.",
        ]
    ini = ["# GENERATED by scripts/catalog/generate_c3.py from cbs_calibration.json and flows.csv.", *status_lines]
    rows, screens = [], {}
    for load in range(4):
        ini += ["", f"[Config C3RatesL{load}]"]
        totals = defaultdict(int)
        for (entry_load, egress, tc), entry in sorted(calibrated.items()):
            if entry_load != load:
                continue
            bps = entry["bps"]
            port_rate = capacity_bps(egress)
            algorithm = f"*.{egress}.macLayer.queue.transmissionSelectionAlgorithm[{tc}]"
            ini.append(f'{algorithm}.typename = "Ieee8021qCreditBasedShaper"')
            ini.append(f"{algorithm}.idleSlope = {bps}bps")
            totals[egress] += bps
            rows.append({"load": f"L{load}", "egress": egress, "traffic_class": tc,
                         "permanent_flows": ";".join(entry["flows"]),
                         "nominal_idle_slope_bps": entry["nominal_bps"],
                         "calibrated_to_nominal_ratio": f"{entry['ratio']:.9f}",
                         "calibrated_idle_slope_bps": bps,
                         "port_rate_bps": port_rate,
                         "total_reservation_at_egress_bps": 0})
        for row in rows:
            if row["load"] == f"L{load}":
                row["total_reservation_at_egress_bps"] = totals[row["egress"]]
        screens[f"L{load}"] = {
            egress: {"total_cbs_reservation_bps": total,
                     "port_rate_bps": capacity_bps(egress),
                     "fraction": total / capacity_bps(egress),
                     "admissible": total <= CAP * capacity_bps(egress)}
            for egress, total in sorted(totals.items())
        }
    csv_data = ["load,egress,traffic_class,permanent_flows,nominal_idle_slope_bps,calibrated_to_nominal_ratio,calibrated_idle_slope_bps,port_rate_bps,total_reservation_at_egress_bps"]
    for r in rows:
        csv_data.append(",".join(str(r[key]) for key in (
            "load", "egress", "traffic_class", "permanent_flows", "nominal_idle_slope_bps",
            "calibrated_to_nominal_ratio", "calibrated_idle_slope_bps", "port_rate_bps",
            "total_reservation_at_egress_bps")))
    screen = {"cap_fraction": CAP, "ratios_file": str(path.relative_to(ROOT)),
              "calibration_status": calibration.get("status", "not_recorded"),
              "ratios_frozen": frozen,
              "calibration": calibration, "screens": screens,
              "inadmissible_loads": [load for load, egresses in screens.items()
                                     if any(not item["admissible"] for item in egresses.values())]}
    return "\n".join(ini) + "\n", "\n".join(csv_data) + "\n", screen


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--ratios", type=Path, default=RATIOS)
    args = parser.parse_args()
    ratios = args.ratios if args.ratios.is_absolute() else ROOT / args.ratios
    ini, csv_data, screen = render(ratios)
    outputs = [(INI_OUT_C3, ini), (CSV_OUT, csv_data), (SCREEN_OUT, json.dumps(screen, indent=2) + "\n")]
    if args.check:
        stale = [str(p.relative_to(ROOT)) for p, content in outputs if not p.exists() or p.read_text() != content]
        if stale:
            raise SystemExit("Stale C3 generated artifacts: " + ", ".join(stale))
    else:
        for path, content in outputs:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print(f"C3 generated/screened {len(screen['screens'])} load profiles; "
          f"inadmissible: {', '.join(screen['inadmissible_loads']) or 'none'}")


if __name__ == "__main__":
    main()

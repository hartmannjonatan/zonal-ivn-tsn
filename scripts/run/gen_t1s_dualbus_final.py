#!/usr/bin/env python3
"""Final statistics for the dual-bus T1S study: 1 s warm-up + 30 s measurement,
seeds 1001-1010 (P1 timing, as in F6), for the baseline (random phases) and the
step-2 schedule (synchronized releases + TC3 gate closed 400 us of every ms).

Writes simulations/zonal/configs/t1s_dualbus_final.ini and the entry point
simulations/zonal_t1s_dualbus_final.ini (run with -n ...:../prioplca -l ../prioplca/prioplca).
"""
from pathlib import Path

SIM = Path(__file__).resolve().parents[2] / "simulations"
BASES = ["T1S_DUAL_1ms_S3", "T1S_DUAL_1ms_S3_SYNCTAS4", "T1S_PT_NOMINAL", "T1S_PT_NOMINAL_SYNCTAS4",
         "T1S_PT_STRESS", "T1S_PT_STRESS_SYNCTAS4"]

L = ["# GENERATED by scripts/run/gen_t1s_dualbus_final.py. Do not edit.",
     "# 30 s / 10-seed runs of the dual-bus and powertrain T1S scenarios.", ""]
for b in BASES:
    L += [f"[Config {b}_30s]", f"extends = {b}",
          f'description = "{b}, 1 s warm-up + 30 s measurement, seeds 1001-1010"',
          f"result-dir = results/t1s/final/{b}_30s",
          "# The 2 s base declares ${seed=1001,1002,1003}; it cannot be redefined, so a new",
          "# variable carries the 10 seeds and the constraint keeps one value of the old one.",
          "seed-set = ${finalSeed=1001..1010}", "constraint = $seed == 1001",
          "sim-time-limit = 31.05s", "warmup-period = 1s",
          "*.trafficPlan.warmup = 1s", "*.trafficPlan.measurement = 30s", ""]
(SIM / "zonal/configs/t1s_dualbus_final.ini").write_text("\n".join(L))
(SIM / "zonal_t1s_dualbus_final.ini").write_text(
    "# Entry point for the dual-bus/powertrain final statistics (needs ../prioplca).\n"
    "include zonal_t1s.ini\ninclude zonal/configs/t1s_dualbus.ini\n"
    "include zonal/configs/t1s_powertrain.ini\ninclude zonal/configs/t1s_dualbus_final.ini\n")
print("written t1s_dualbus_final.ini, zonal_t1s_dualbus_final.ini")

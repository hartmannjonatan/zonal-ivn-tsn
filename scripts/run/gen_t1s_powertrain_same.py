#!/usr/bin/env python3
"""Powertrain scenario with BOTH 10BASE-T1S buses on the SAME zonal switch (Z1).

Same nodes, flows, schedule and clocks as gen_t1s_powertrain.py /
gen_t1s_dualbus_clock.py, except the topology:
  Bus A: Z1.ZSW eth5 (WINDOW1's port, as before): ZSW 0, WINDOW1 1, ECM 2, ETC 3, MAP 4, LAMBDA 5
  Bus B: Z1.ZSW eth9 (new 8th access port, Z1.numAccessPorts = 8): ZSW 0, TCU 1, APP 2, GEAR 3, OSS 4
WINDOW3 stays on its original 100 Mb/s link in Z3, so bus B carries no window
traffic (5 PLCA nodes instead of 6). Cross-bus traffic is switched inside Z1.ZSW and
no longer crosses the CSW or the 1 Gb/s links.

Reads the generated t1s_powertrain.ini and t1s_dualbus_clock.ini (run their
generators first) and writes:
  simulations/zonal/networks/ZonalIVNT1SPowertrainSame.ned
  simulations/zonal/configs/t1s_powertrain_same.ini   (T1S_PTS_* configs)
  simulations/zonal_t1s_powertrain_same.ini            (needs ../prioplca for -l)
"""
import re
from pathlib import Path

import gen_t1s_powertrain as G

SIM = G.SIM
BUS_A = G.BUS[1]
BUS_B = [(n, i + 1, icon, pos) for i, (n, _, icon, pos) in enumerate(G.BUS[3])]
NODES_A, NODES_B = 2 + len(BUS_A), 1 + len(BUS_B)
PORT_A, PORT_B = 5, 9


def network():
    s = (SIM / "zonal/networks/ZonalIVN.ned").read_text()
    s = s.replace("import zonal_ivn_tsn.common.TrafficAudit;\n",
                  "import zonal_ivn_tsn.common.TrafficAudit;\nimport inet.node.ethernet.EthernetMultidropLink;\n"
                  "import inet.physicallayer.wired.common.WireJunction;\n")
    s = s.replace("// Complete physical P1 topology. Traffic catalog and C0-C4 are configured separately.\nnetwork ZonalIVN\n{",
                  "// GENERATED by scripts/run/gen_t1s_powertrain_same.py. Powertrain variant with both\n"
                  "// 10BASE-T1S buses on Z1.ZSW: bus A on eth5 (replaces WINDOW1's link), bus B on a new\n"
                  "// access port eth9. All other links unchanged (WINDOW3 keeps its 100 Mb/s link).\n"
                  "network ZonalIVNT1SPowertrainSame\n{")
    s = s.replace('text="ZONAL IVN"', 'text="ZONAL IVN | POWERTRAIN T1S, SAME SWITCH"')
    s = s.replace("        bool hasTraffic = default(false);\n",
                  "        bool hasTraffic = default(false);\n"
                  f"        int plcaCountA = default({NODES_A});\n        int plcaCountB = default({NODES_B});\n", 1)
    pat = "        Z1: ZonalController {\n"
    assert pat in s
    s = s.replace(pat, pat + f'''            numAccessPorts = 8;
            ZSW.eth[{PORT_A}].typename = "EthernetPlcaInterface";
            ZSW.eth[{PORT_A}].plca.plca_node_count = parent.plcaCountA;
            ZSW.eth[{PORT_A}].plca.local_nodeID = 0;
            ZSW.eth[{PORT_B}].typename = "EthernetPlcaInterface";
            ZSW.eth[{PORT_B}].plca.plca_node_count = parent.plcaCountB;
            ZSW.eth[{PORT_B}].plca.local_nodeID = 0;
''')
    pat = "        WINDOW1: TsnDevice {\n            numEthInterfaces = 1;\n"
    assert pat in s
    s = s.replace(pat, pat + '''            eth[0].typename = "EthernetPlcaInterface";
            eth[0].plca.plca_node_count = parent.plcaCountA;
            eth[0].plca.local_nodeID = 1;
''')
    link = G.WINDOW_LINK[1]
    i = s.index(f"        {link}")
    j = s.index("\n", s.index("        } <-->", i)) + 1
    conn = '''        Z1.access[3] <--> T1S_A_SW: EthernetMultidropLink {
            length = 100cm;
            @display("ls=#a855f7,1;tt=10BASE-T1S bus A | 10 Mbit/s | PLCA");
        } <--> T1SA.port++;
        T1SA.port++ <--> T1S_A_WINDOW1: EthernetMultidropLink {
            length = 50cm;
        } <--> WINDOW1.ethg[0];
'''
    for name, *_ in BUS_A:
        conn += f'''        T1SA.port++ <--> T1S_A_{name}: EthernetMultidropLink {{
            length = 50cm;
        }} <--> {name}.ethg[0];
'''
    conn += '''        Z1.access[7] <--> T1S_B_SW: EthernetMultidropLink {
            length = 100cm;
            @display("ls=#a855f7,1;tt=10BASE-T1S bus B | 10 Mbit/s | PLCA");
        } <--> T1SB.port++;
'''
    for name, *_ in BUS_B:
        conn += f'''        T1SB.port++ <--> T1S_B_{name}: EthernetMultidropLink {{
            length = 50cm;
        }} <--> {name}.ethg[0];
'''
    s = s[:i] + conn + s[j:]
    subs = '''        T1SA: WireJunction {
            @display("p=760,215;is=vs;t=T1S bus A");
        }
        T1SB: WireJunction {
            @display("p=760,120;is=vs;t=T1S bus B");
        }
'''
    for bus, cnt in ((BUS_A, "plcaCountA"), (BUS_B, "plcaCountB")):
        for name, pid, icon, pos in bus:
            subs += f'''        {name}: TsnDevice {{
            numEthInterfaces = 1;
            eth[0].typename = "EthernetPlcaInterface";
            eth[0].plca.plca_node_count = parent.{cnt};
            eth[0].plca.local_nodeID = {pid};
            @display("p={pos};i={icon};is=vs;t={name}");
        }}
'''
    s = s.replace("    connections:\n", subs + "    connections:\n", 1)
    (SIM / "zonal/networks/ZonalIVNT1SPowertrainSame.ned").write_text(s)


def tables():
    cb = (SIM / "zonal/configs/catalog-bindings.ini").read_text()
    out = {}
    for sw in ("CSW", "Z1.ZSW", "Z3.ZSW"):
        t = re.search(rf"^\*\.{re.escape(sw)}\.macTable\.forwardingTable = \[(.*)\]$", cb, re.M).group(1)
        extra = []
        for bus, port in ((BUS_A, PORT_A), (BUS_B, PORT_B)):
            for name, *_ in bus:
                p = "eth1" if sw == "CSW" else (f"eth{port}" if sw == "Z1.ZSW" else "eth0")
                extra.append(f'{{address: "{name}", interface: "{p}", vlan: {G.VLAN}}}')
        out[sw] = "[" + t + ", " + ", ".join(extra) + "]"
    return out


def sections(text):
    out = {}
    for part in text.split("\n[Config ")[1:]:
        name, body = part.split("]\n", 1)
        out[name] = body.rstrip("\n").split("\n")
    return out


def transform(lines, tbl):
    res = []
    for l in lines:
        if l.startswith("*.WINDOW3.eth[0].") or "plcaCountZ" in l or "slotOwners" in l:
            continue
        if l.startswith("network = "):
            l = "network = zonal_ivn_tsn.simulations.zonal.networks.ZonalIVNT1SPowertrainSame"
        m = re.match(r"\*\.(CSW|Z1\.ZSW|Z3\.ZSW)\.macTable\.forwardingTable = ", l)
        if m:
            l = f"*.{m.group(1)}.macTable.forwardingTable = {tbl[m.group(1)]}"
        l = l.replace("Z3.ZSW.eth[6]", "Z1.ZSW.eth[9]").replace("^.^.^.Z3.ZSW.clock", "^.^.^.Z1.ZSW.clock")
        l = l.replace("T1SPowertrainNetwork", "T1SPowertrainSameNetwork").replace("T1S_PT_", "T1S_PTS_")
        l = l.replace("results/t1s/T1S_PT", "results/t1s/T1S_PTS").replace("results/t1s/final/T1S_PT_", "results/t1s/final/T1S_PTS_")
        res.append(l)
    return res


def final_30s(cfg):
    return [f"[Config {cfg}_30s]", f"extends = {cfg}",
            f'description = "{cfg}, 1 s warm-up + 30 s measurement, seeds 1001-1010"',
            f"result-dir = results/t1s/final/{cfg}_30s",
            "seed-set = ${finalSeed=1001..1010}", "constraint = $seed == 1001",
            "sim-time-limit = 31.05s", "warmup-period = 1s",
            "*.trafficPlan.warmup = 1s", "*.trafficPlan.measurement = 30s", ""]


def ini():
    tbl = tables()
    pt = sections((SIM / "zonal/configs/t1s_powertrain.ini").read_text())
    ck = sections((SIM / "zonal/configs/t1s_dualbus_clock.ini").read_text())
    keep = ["T1SPowertrainNetwork"]
    for p in ("NOMINAL", "STRESS"):
        keep += [f"T1S_PT_{p}", f"T1S_PT_{p}_SYNC", f"T1S_PT_{p}_SYNCTAS", f"T1S_PT_{p}_SYNCTAS4"]
    L = ["# GENERATED by scripts/run/gen_t1s_powertrain_same.py. Do not edit.",
         "# Powertrain with both T1S buses on Z1.ZSW (eth5, eth9); derived from t1s_powertrain.ini",
         "# and t1s_dualbus_clock.ini.", ""]
    for name in keep:
        L += [f"[Config {name.replace('T1SPowertrainNetwork', 'T1SPowertrainSameNetwork').replace('T1S_PT_', 'T1S_PTS_')}]"]
        L += transform(pt[name], tbl) + [""]
    for p in ("NOMINAL", "STRESS"):
        name = f"T1S_PT_{p}_SYNCTAS4_GPTP"
        L += [f"[Config {name.replace('T1S_PT_', 'T1S_PTS_')}]"] + transform(ck[name], tbl) + [""]
        L += final_30s(f"T1S_PTS_{p}") + final_30s(f"T1S_PTS_{p}_SYNCTAS4_GPTP")
    (SIM / "zonal/configs/t1s_powertrain_same.ini").write_text("\n".join(L))
    (SIM / "zonal_t1s_powertrain_same.ini").write_text(
        "# Entry point for the same-switch powertrain variant (needs ../prioplca for -l).\n"
        "include zonal_t1s.ini\ninclude zonal/configs/t1s_powertrain_same.ini\n")


if __name__ == "__main__":
    network()
    ini()
    print("written ZonalIVNT1SPowertrainSame.ned, t1s_powertrain_same.ini, zonal_t1s_powertrain_same.ini")

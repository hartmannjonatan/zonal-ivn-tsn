#!/usr/bin/env python3
"""Generate the Fever CAN traffic configs on the hybrid T1S network (follow-up F4).

Flow set: simulations/zonal/traffic/fever/flows.json (47 CAN IDs from the Fever
FR250 trace, from plca-priority-to). Each CAN message becomes a periodic UDP
flow to HPC (one UdpSink per CAN ID, port 8000 + index), with the period and
phase of the trace and deadline = period. Payload 36 B = IEEE 1722 NTSCF (12 B)
+ ACF CAN (16 B) + 8 data bytes, as in plca-priority-to; this model is IP-based,
so UDP/IPv4 adds 28 B (86 B MAC frame instead of 64 B raw Ethernet, conservative).
VLAN 31, PCP 2 (same as the body status flows of F3).

Variants (network ZonalIVNT1SHybrid: radar/brake on 100 Mb/s, WINDOW on T1S):
  T1S_FEVER_ECU : one T1S node per sending ECU. ECU = source address (last byte of
                  29-bit IDs); all 11-bit IDs form one ECU. The 19 ECUs are spread over
                  the three zones in snake order of load, 6 body nodes per zone
                  (8 nodes/segment, the IEEE 802.3cg limit); the two lightest ECUs
                  (1 frame/s each) share one node so that 19 ECUs fit 18 slots.
  T1S_FEVER_GW  : one CAN-to-Ethernet gateway node on Z1's segment sends all 47 IDs
                  (bodyNodes = 1; B2[0]/B3[0] idle) -> 3 nodes on each segment.
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_t1s_hybrid import tables  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
SIM = ROOT / "simulations"
FLOWS = json.loads((SIM / "zonal/traffic/fever/flows.json").read_text())
PAYLOAD = 36
PORT0 = 8000
SLOTS = 6   # body nodes per zone: 2 + 6 = 8 nodes per segment (IEEE 802.3cg limit)


def ecu(can_id):
    return can_id[-2:] if len(can_id) == 8 and int(can_id, 16) > 0x7FF else "STD"


def ecu_assignment():
    groups = defaultdict(list)
    for f in FLOWS:
        groups[ecu(f["id"])].append(f)
    load = lambda g: sum(1000 / f["period_ms"] for f in groups[g])
    order = sorted(groups, key=lambda g: -load(g))
    while len(order) > 3 * SLOTS:          # merge the two lightest ECUs into one node
        a, b = order.pop(), order.pop()
        groups[f"{b}+{a}"] = groups.pop(b) + groups.pop(a)
        order.append(f"{b}+{a}")
        order.sort(key=lambda g: -load(g))
    snake = [1, 2, 3, 3, 2, 1]
    nodes = defaultdict(list)                     # zone -> list of ECU groups
    for k, g in enumerate(order):
        nodes[snake[k % 6]].append(g)
    return groups, nodes


def app_lines(node, flows):
    out = [f"*.{node}.numApps = {len(flows)}", f'*.{node}.app[*].typename = "UdpSourceApp"',
           f'*.{node}.app[*].io.destAddress = "HPC"', f'*.{node}.app[*].source.packetNameFormat = "CAN-%c"',
           f"*.{node}.app[*].source.packetLength = {PAYLOAD}B"]
    for k, f in enumerate(flows):
        out += [f"*.{node}.app[{k}].io.destPort = {PORT0 + f['index']}   # {f['id']} {f['class']}",
                f"*.{node}.app[{k}].source.productionInterval = {f['period_ms']}ms",
                f"*.{node}.app[{k}].source.initialProductionOffset = {f['phase_ms']:g}ms"]
    return out


def common(n):
    t = tables(n)
    return [f"*.bodyNodes = {n}",
            f"*.HPC.numApps = {20 + len(FLOWS)}",
            '*.HPC.app[20..].typename = "UdpSink"',
            f"*.HPC.app[20..].localPort = {PORT0} + index - 20",
            "**.HPC.app[*].endToEndDelay:vector.vector-recording = true",
            f'*.B*[*].bridging.streamIdentifier.identifier.mapping = [{{stream: "BU", packetFilter: expr(udp.destPort >= {PORT0})}}]',
            "*.B*[*].hasIncomingStreams = false"] + [
        f"*.{sw}.macTable.forwardingTable = {t[sw]}" for sw in ("CSW", "Z1.ZSW", "Z2.ZSW", "Z3.ZSW")]


def main():
    groups, nodes = ecu_assignment()
    L = ["# GENERATED by scripts/run/gen_t1s_fever.py. Do not edit.",
         "# Fever FR250 CAN flows (47 IDs, 872 frames/s) as UDP flows from T1S nodes to HPC.", ""]
    L += ["[Config T1S_FEVER_ECU]", "extends = T1SHybridNetwork, C0_L1_A0_2s",
          'description = "Hybrid T1S + Fever CAN trace, one T1S node per ECU (6 body nodes per zone)"',
          "result-dir = results/t1s/T1S_FEVER_ECU"] + common(SLOTS)
    for z in (1, 2, 3):
        for i in range(SLOTS):
            if i < len(nodes[z]):
                g = nodes[z][i]
                L.append(f"# B{z}[{i}] = ECU {g}: {len(groups[g])} CAN IDs, "
                         f"{sum(1000 / f['period_ms'] for f in groups[g]):.0f} frames/s")
                L += app_lines(f"B{z}[{i}]", groups[g])
            else:
                L += [f"# B{z}[{i}] idle", f"*.B{z}[{i}].numApps = 0"]
    L += ["", "[Config T1S_FEVER_GW]", "extends = T1SHybridNetwork, C0_L1_A0_2s",
          'description = "Hybrid T1S + Fever CAN trace through one gateway node on Z1 (all 47 IDs)"',
          "result-dir = results/t1s/T1S_FEVER_GW"] + common(1)
    L += ["# B1[0] = CAN-to-Ethernet gateway with all 47 IDs; B2[0], B3[0] idle"] + app_lines("B1[0]", FLOWS)
    L += ["*.B2[0].numApps = 0", "*.B3[0].numApps = 0", ""]
    (SIM / "zonal/configs/t1s_fever.ini").write_text("\n".join(L))
    (SIM / "zonal_t1s_fever.ini").write_text("# Entry point for the Fever CAN scenario (follow-up F4).\n"
                                             "include zonal_t1s_hybrid.ini\ninclude zonal/configs/t1s_fever.ini\n")
    for z in (1, 2, 3):
        print(f"Z{z}:", [(g, len(groups[g]), round(sum(1000 / f['period_ms'] for f in groups[g]))) for g in nodes[z]])


if __name__ == "__main__":
    main()
